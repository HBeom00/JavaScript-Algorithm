function solution(n) {
  let result = "";
  const arr = ["4", "1", "2"];

  while (n > 0) {
    const rest = n % 3;

    result = arr[rest] + result;

    n = Math.floor(n / 3);

    if (rest === 0) n--;
  }
  return result;
}

